var services = { //оголошення об'єкту через змінну services яка має 3 властивості
    "стрижка": "60 грн",
    "гоління": "80 грн",
    "Миття голови": "100 грн",

    price: function() { //price - метод об'єкта services, який буде обчислювати загальну вартість усіх послуг
        let total = 0; // Змінна для зберігання загальної вартості
        for (let service in this) {/*цикл перебирає всі властивості об'єкта services. 
            Кожна назва властивості зберігається в змінній service*/
            if (typeof this[service] === "string") {//Перевірка, чи є значення властивості рядком
                total += parseInt(this[service]); /*перетворення рядка з вартістю у ціле число ігноруючи грн
                 і додаємо це число до змінної total*/
            }
        }
        return total + " грн"; // Повертаємо загальну вартість додаючи грн
    },

    minPrice: function() {//оголошення методу для обчислення мінімальної вартості послуг
        let min = Infinity; /* Оголошення змінної зі знченням Infinity бо це значення, 
        яке завжди більше за будь-яке інше число. Таким чином, ми можемо шукати мінімум*/
        for (let service in this) {
            if (typeof this[service] === "string") {
                let price = parseInt(this[service]); // Перетворюємо вартість у число
                if (price < min) {
                    min = price; // Якщо знайдена вартість менша за min, оновлюємо min новим значенням.
                }
            }
        }
        return min + " грн"; // Повертаємо мінімальну вартість додаючи грн
    },

    // Метод для отримання максимальної вартості
    maxPrice: function() {
        let max = -Infinity; // Початкова максимальна вартість
        for (let service in this) {
            if (typeof this[service] === "string") {
                let price = parseInt(this[service]); // Перетворюємо вартість у число
                if (price > max) {
                    max = price; // Оновлюємо максимальну вартість
                }
            }
        }
        return max + " грн"; // Повертаємо максимальну вартість
    }
};

services['Розбити скло'] = "200 грн"; // Додавання нової послуги

// Використання методів
console.log("Загальна вартість послуг: " + services.price()); // Виведе загальну вартість
console.log("Мінімальна вартість послуги: " + services.minPrice()); // Виведе мінімальну вартість
console.log("Максимальна вартість послуги: " + services.maxPrice()); // Виведе максимальну вартість
